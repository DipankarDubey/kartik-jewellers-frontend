import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const base='https://kartik-jewellers.onrender.com';
const api='https://kartik-jewellers-api.onrender.com/api';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1366,height:900}});
try{
  await page.goto(base+'/#/',{waitUntil:'domcontentloaded',timeout:90000});
  await page.getByRole('heading',{name:/Timeless jewellery/i}).waitFor({timeout:60000});
  assert.equal(await page.getByRole('link',{name:/Admin Login/i}).count(),1);
  const logo=page.locator('header img.brand-emblem');
  await logo.waitFor();
  await logo.evaluate(async img=>{if(!img.complete)await new Promise((resolve,reject)=>{img.onload=resolve;img.onerror=reject})});
  assert.ok(await logo.evaluate(img=>img.naturalWidth>0),'Logo failed to load');
  console.log('PASS live homepage, shop logo and visible admin login');
  await page.goto(base+'/#/collections');
  await page.getByRole('heading',{name:'Our jewellery collections'}).waitFor();
  await page.getByText('Showing 6 designs').waitFor({timeout:60000});
  await page.waitForFunction(()=>[...document.querySelectorAll('.product-card img')].length===6&&[...document.querySelectorAll('.product-card img')].every(img=>img.complete&&img.naturalWidth>0),null,{timeout:60000});
  console.log('PASS six live Cloudinary product images loaded');
  await page.getByRole('button',{name:'Rings',exact:true}).click();
  await page.getByText('Showing 1 designs').waitFor();
  await page.getByText('Classic Diamond Ring').waitFor();
  await page.getByRole('button',{name:'All',exact:true}).click();
  await page.getByPlaceholder('Search designs...').fill('Necklace');
  await page.getByText('Showing 2 designs').waitFor();
  console.log('PASS live category filtering and product search');
  await page.goto(base+'/#/location');
  await page.getByRole('heading',{name:'Visit our showroom'}).waitFor();
  await page.goto(base+'/#/contact');
  await page.getByRole('heading',{name:'Contact us'}).waitFor();
  console.log('PASS location and contact pages');
  await page.goto(base+'/#/admin/products');
  await page.getByRole('heading',{name:'Welcome back'}).waitFor();
  console.log('PASS private admin route redirects to login');
  const unauthorized=await page.request.post(api+'/admin/upload',{multipart:{image:{name:'test.png',mimeType:'image/png',buffer:Buffer.from([137,80,78,71])}}});
  assert.equal(unauthorized.status(),401);
  console.log('PASS production upload endpoint blocks unauthorized users');
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await mobile.goto(base+'/#/',{waitUntil:'domcontentloaded',timeout:90000});
  await mobile.locator('.hamburger').click();
  await mobile.getByRole('link',{name:/Admin Login/i}).waitFor();
  console.log('PASS mobile navigation exposes admin login');
  await mobile.close();
} finally {await browser.close()}
